"""Pins wm's runtime dependencies, with their hashes, for the wm bundled into Workstreams.app.

    .venv/bin/python macos/scripts/pin-wm-deps.py > macos/wm-requirements.txt

Run it after changing pyproject.toml's dependencies. The versions are the ones installed in the venv, so the ones the
tests ran against; the hashes come from PyPI, for the wheels a Mac can install.
"""

import importlib.metadata as md
import json
import sys
import urllib.request

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

PYTHON_TAG = "cp312"  # the bundled Python: macos/scripts/bundle-wm.sh


def walk(name: str, extras: set[str], pins: dict[str, tuple[str, set[str]]]) -> None:
    for spec in md.requires(name) or []:
        req = Requirement(spec)
        if req.marker and not any(req.marker.evaluate({"extra": e}) for e in extras | {""}):
            continue
        dist = md.distribution(req.name)
        key = canonicalize_name(dist.metadata["Name"])
        seen = pins.get(key, (dist.version, set()))[1]
        if key not in pins or not req.extras <= seen:
            pins[key] = (dist.version, seen | req.extras)
            walk(req.name, req.extras, pins)


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as reply:
        files = json.load(reply)["urls"]
    def for_mac(wheel: str) -> bool:
        return wheel.endswith("-none-any.whl") or (PYTHON_TAG in wheel and "macosx" in wheel)

    wheels = [f for f in files if f["packagetype"] == "bdist_wheel" and for_mac(f["filename"])]
    if not wheels:
        sys.exit(f"{name}=={version} has no wheel for macOS")
    return sorted(f["digests"]["sha256"] for f in wheels)


def main() -> None:
    pins: dict[str, tuple[str, set[str]]] = {}
    walk("agentmgr", set(), pins)
    print("# wm's runtime dependencies, for the wm inside Workstreams.app. Generated by macos/scripts/pin-wm-deps.py")
    for name, (version, _) in sorted(pins.items()):
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes(name, version)))


if __name__ == "__main__":
    main()
