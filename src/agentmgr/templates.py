"""Generated workstream files: CLAUDE.md and .claude/settings.json (both manager-owned)."""

from __future__ import annotations

import json
import os
import shlex
from pathlib import Path

from . import ledger
from .db import RepoLink, Workstream

TASK_FILE = "TASK.md"

TASK_FORMAT = """\
---
key: {key}
ticket: {ticket}
name: {name}
---
## Goal
## Context
(what the user said, cleaned up — keep their wording where it matters)
## Done when
- [ ] checkable acceptance criteria
## Out of scope
(questions for the user, facts, rules and progress go in the brief with the `wm` commands, not here)"""


def claude_md(ws: Workstream, repos: list[RepoLink], available_repos: list[str], memory_dir: Path,
              pending_repos: list[str] | None = None) -> str:
    key = ws.key
    title = " · ".join(p for p in (key, ws.ticket if ws.ticket != key else None, ws.name) if p)
    has_task = (ws.path / TASK_FILE).exists()
    out: list[str] = [f"# Workstream {title}", ""]
    out += [
        "This folder is the root of a workstream managed by `wm` (agents manager). Each subfolder listed under",
        "Repos is a git worktree dedicated to this workstream. This file is regenerated by `wm`; don't edit it.",
        "",
    ]
    if (ws.path / ledger.BRIEF_IMPORT).exists():
        out += [f"@{ledger.BRIEF_IMPORT}", ""]
    if has_task:
        out += [f"@{TASK_FILE}", ""]
    else:
        pending = ""
        if pending_repos:
            pending = f" The user already selected these repos: {', '.join(pending_repos)}."
        fmt = TASK_FORMAT.format(key=key, ticket=ws.ticket or "", name=ws.name or "<3 words>")
        out += [
            f"## Intake — do this first ({TASK_FILE} does not exist yet)",
            "",
            "The user will describe the task, often by voice (expect transcription errors), possibly mentioning",
            f"a ticket id like PROJ-313 and the repos to work in.{pending} Then, in this order:",
            "",
            f"1. Name the workstream: `wm set {key} --name \"<3-word summary>\"` and, if the user mentioned a",
            "   ticket, add `--ticket <ID>`. Lowercase, max 3 words, e.g. \"dark mode toggle\".",
            f"2. Write `{TASK_FILE}` in this folder using the format below.",
            f"3. Attach every repo: `wm add-repo {key} <repo>` (add `--branch <name>` only if the user asked to",
            "   continue an existing branch). Repo names are fuzzy-matched; if the command lists candidates,",
            "   pick the right one or ask. The command creates the worktree and branch — never do it yourself.",
            "   If the user wants to continue work already in progress in a repo's normal checkout (a branch",
            f"   and/or uncommitted changes in ~/code/<repo>), use `wm add-repo {key} <repo> --adopt` instead: it",
            "   prints a plan (stash, free the branch, move it into the worktree); show it to the user and, once",
            "   they agree, rerun it with `--yes`.",
            "4. Summarise back: name, ticket, goal, repos + branches, done-when. Put each open question in the",
            "   brief with `wm ask` (see \"The brief\" below) rather than in the summary.",
            "5. **Wait for the user to confirm before changing any code.**",
            "",
            f"Available repos: {', '.join(available_repos) or '(none found)'}",
            "",
            f"{TASK_FILE} format:",
            "",
            "```markdown",
            fmt,
            "```",
            "",
        ]

    out += ["## Repos", ""]
    if repos:
        out += ["| Folder | Repo | Branch | Base | Original checkout (read-only) |", "|---|---|---|---|---|"]
        for r in repos:
            folder = Path(r.worktree_path).name + "/"
            out.append(f"| {folder} | {r.repo} | {r.branch} | {r.base} | {r.repo_path} |")
        imports = repo_instruction_imports(repos)
        if imports:
            # Claude Code loads a subfolder's CLAUDE.md only once Claude reads or edits a file there, and a compaction
            # summarises it away until that happens again; imported here, it holds from the first message and is
            # re-read from disk after every compaction, with the rest of this file.
            out += ["", "Each repo's own instructions, which apply to all work in that repo:", ""]
            out += [f"@{path}" for path in imports]
    else:
        out.append("(none attached yet)")
    ident = ws.ticket or key
    # Also during intake: the first session starts then and usually carries on with the task, and a running session
    # re-reads this file only after a compaction, so a rule added only once TASK.md exists could miss the session that
    # does the work.
    scope = (f"This session is for {title} only." if has_task
             else "Once intake has set this workstream's task, this session is for that task only.")
    out += [
        "",
        "## Rules",
        "",
        f"- {scope}",
        "  Several workstreams run side by side and the user switches between them, so a message can land in",
        f"  the wrong session. Before acting on a request, check that it fits this workstream's goal in {TASK_FILE}.",
        "  If it is about another workstream's work (its repos, branches, PRs, artifacts or anything in another",
        "  workstream folder) or plainly unrelated to this task, don't act on it: say it looks meant for another",
        "  workstream (name it if you can tell, `wm ls` lists them) and go ahead here only if the user confirms.",
        "  Quick general questions are fine to answer.",
        f"- Only modify files inside the repo subfolders above and {TASK_FILE} (plus your memory folder and your",
        "  scratchpad). The original checkouts are read-only reference.",
        "- Never create, remove or move git worktrees, and never switch branches in these worktrees.",
        "  Guard hooks enforce this; if a command is blocked, read the reason and adjust.",
        "  To look at another branch use `git show <branch>:<path>` or `git diff <branch>`.",
        f"- Need another repo? Run `wm add-repo {key} <repo>` (add `--adopt` to bring in work in progress from",
        "  its normal checkout). Never clone or cd elsewhere.",
        "- Run git commands from inside the repo subfolder (e.g. `cd acme-web && git status`).",
        f"- Commit in each repo separately; mention {ident} in commit messages.",
        f"- Open PRs with `gh pr create` from inside the worktree when asked; include {ident} in the title.",
        "  If a PR has to come from another branch (a stack, a re-cut branch), start that branch's name with",
        f"  `{ident.lower()}-` (e.g. `{ident.lower()}-part-2`) so wm shows its PR with this workstream.",
        "",
    ]
    out += brief_section(key)
    out += [
        "## Memory",
        "",
        f"Your memory folder, {memory_dir}, is shared by every workstream:",
        "what you save there shows up in all of them. Save there only what applies to any task: how the user",
        "likes to work, feedback on your behaviour, useful references.",
        "- Facts about this task (decisions, findings, state) go in the brief: `wm fact`, `wm changed`.",
        "- Facts about one repo (commands, conventions, gotchas) belong in that repo's CLAUDE.md in its worktree;",
        "  it gets committed, so propose the change to the user first.",
        "- Don't save \"project\"-type memories about this workstream: every other workstream would load them.",
        "",
        "## Done means",
        "",
        f"- Every \"Done when\" item in {TASK_FILE} is checked.",
        "- Everything is committed and pushed in every repo; report any repo left dirty or unpushed.",
        "- Don't clean up worktrees or branches — the user archives the workstream with `wm`.",
        "",
    ]
    return "\n".join(out)


def brief_section(key: str) -> list[str]:
    """How Claude talks to the user through the app's Brief panel (ledger.py)."""
    return [
        "## The brief: questions, facts, rules and what changed",
        "",
        "The user follows this workstream in the Workstreams app, which shows a Brief panel beside the chat: what",
        "waits on them, what you are doing, and the rules, facts and changes so far. It is built from",
        f"`.wm/ledger.json` ({ledger.BRIEF_IMPORT} above is its readable copy), which you write only with these",
        "pre-approved commands. Keep it current: in the same turn you decide, learn or change something, record it.",
        "",
        "- **Questions for the user** (decisions, assumptions to check, things only they can unblock):",
        f"  `wm ask {key} \"<question>\" --context \"<what it is about and why it matters>\"",
        "  --option \"<label> | <what this option does to the result>\" --option \"…\" --recommended <n>",
        "  --if-no-answer \"<what you will do if they don't answer>\"`. Add `--assumption` to check something you",
        "  assumed, `--blocker` for a login, permission or anything only they can do (options optional then).",
        "  Write each question so it makes sense on its own to someone who hasn't read the chat: the user's words,",
        "  no internal ids or code names unless explained, and for each option what happens to the result. If the",
        "  step is hard to undo (deploy, merge, deleting data, writing to production), say that you will wait.",
        "  In the chat, only say in one line how many questions wait in the brief; don't repeat them there.",
        f"- Reword or drop an open question: `wm ask {key} --revise Q2 …` (same options as above) or",
        f"  `wm ask {key} --drop Q2 --reason \"…\"`.",
        f"- **Facts**: `wm fact {key} \"<fact>\" --found` (you checked it), `--assumed` (pair it with an",
        "  `--assumption` question and pass `--question Q3`) or `--you` (the user said it). Add `--example \"…\"`",
        "  with real ids or rows the user can check. Correct one with `--update F2`, delete with `--remove F2`.",
        f"- **Rules** the user sets (budgets, \"don't deploy\", \"no automerge\"): `wm rule {key} \"<rule>\"`.",
        "  They hold until the user changes them; follow every rule in the brief.",
        f"- **What changed**: when you learn something that changes the plan, `wm changed {key} \"<learned X> →",
        "  <changed Y>\"` and say it in one line in the chat. Use it at milestones too (PR opened, data loaded).",
        "- **Where we are and what's next** (the app's Status card, what the user reads first when they come",
        f"  back): at the end of every turn that did work, `wm state {key} \"<where the work stands, one sentence>\"`.",
        f"  Keep the steps ahead current: `wm step {key} \"<what has to happen>\" [--owner you|job]",
        "  [--waits-on S2|Q1|job]`, `--doing S3` when you start one, `--done S3` when it's finished. Name the steps",
        "  the user has to do (`--owner you`, e.g. a login) and the ones waiting on a job you started (a monitor, a",
        "  background command): the app then shows \"waiting on a job\" instead of \"your turn\".",
        "- **The plan**: when the task has more than one stage (e.g. retrain → evaluate → the user decides →",
        f"  deploy), set the phases out once, early: `wm phase {key} \"<stage>\" [--owner you|job]`, in order. A",
        "  stage where the user decides gets `--owner you --question Q2`, linking the question that decides it.",
        f"  Move the plan as the work moves: `wm phase {key} --start P2` (finishes the phase before it),",
        "  `--done P2`, `--skip P4` (e.g. no deploy after a \"no\"); add, reword (`--update P3`) or `--remove`",
        "  phases when the plan changes, and say why with `wm changed`. Steps belong to the current phase.",
        f"- `wm brief {key}` prints the current brief.",
        "- The user answers questions and edits rules and facts in the app. Those changes reach you as a message",
        "  starting \"[wm] The user updated the brief\": act on them; they are recorded already.",
        "- Keep chat replies short by leaving out status updates and step-by-step narration, not by compressing",
        "  what the user has to act on.",
        "",
    ]


HOOK_EVENTS = {
    "SessionStart": None,
    "UserPromptSubmit": None,
    "PreToolUse": "*",
    "PostToolUse": "*",
    "Notification": None,
    "Stop": None,
    "SessionEnd": None,
}


REPO_INSTRUCTION_FILES = ("CLAUDE.md", ".claude/CLAUDE.md")


def repo_instruction_imports(repos: list[RepoLink]) -> list[str]:
    """`<folder>/CLAUDE.md` for each attached repo whose worktree has one. Only files that exist: Claude Code skips a
    missing import silently, but Claude still sees the line and goes looking for the file."""
    found = []
    for r in repos:
        wt = Path(r.worktree_path)
        found += [f"{wt.name}/{name}" for name in REPO_INSTRUCTION_FILES if (wt / name).is_file()]
    return found


def allowed_tools(ws: Workstream, memory_dir: Path) -> list[str]:
    """Pre-approved tools, passed with --allowedTools rather than written to settings.json: project-level
    allow rules make Claude Code re-ask for folder trust on every new workstream folder."""
    brief = [f"Bash(wm {cmd} {ws.key} *)" for cmd in BRIEF_COMMANDS] + [f"Bash(wm brief {ws.key})"]
    return [f"Bash(wm set {ws.key} *)", f"Bash(wm add-repo {ws.key} *)", *brief, f"Edit(./{TASK_FILE})",
            f"Edit(//{str(memory_dir).strip('/')}/**)"]


BRIEF_COMMANDS = ("ask", "fact", "rule", "changed", "state", "step", "phase")


def settings_json(ws: Workstream, wm: str, checkouts: list[str]) -> str:
    """`checkouts`: code roots and single repos, where edits are denied."""
    hooks: dict[str, list] = {}
    for event, matcher in HOOK_EVENTS.items():
        entry: dict = {"hooks": [{"type": "command", "command": f"{shlex.quote(wm)} hook {event}"}]}
        if matcher:
            entry["matcher"] = matcher
        hooks[event] = [entry]
    deny = ["EnterWorktree", "Agent(isolation:worktree)"]
    # "//" = absolute path in permission rules
    deny += [f"Edit(//{path.strip('/')}/**)" for path in checkouts]
    settings = {
        "permissions": {
            "deny": deny,
        },
        "hooks": hooks,
    }
    return json.dumps(settings, indent=2) + "\n"


def write(ws: Workstream, repos: list[RepoLink], available_repos: list[str], wm: str,
          checkouts: list[str], memory_dir: Path, pending_repos: list[str] | None = None) -> None:
    if not ledger.path(ws.path).exists():
        with ledger.edit(ws.path):  # an empty ledger, so BRIEF.md exists for CLAUDE.md to import
            pass
    _replace(ws.path / "CLAUDE.md", claude_md(ws, repos, available_repos, memory_dir, pending_repos))
    (ws.path / ".claude").mkdir(exist_ok=True)
    _replace(ws.path / ".claude" / "settings.json", settings_json(ws, wm, checkouts))


def _replace(path: Path, text: str) -> None:
    """Write only a change, and in one step: Claude Code may be reading the file right then (it re-reads CLAUDE.md
    after a compaction, and watches settings.json), and must never see it empty or half-written."""
    try:
        if path.read_text() == text:
            return
    except OSError:
        pass
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    tmp.write_text(text)
    os.replace(tmp, path)
